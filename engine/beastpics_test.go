package engine

import (
	"flag"
	"fmt"
	"os"
	"slices"
	"strconv"
	"strings"
	"testing"
)

var updatePics = flag.Bool("update", false, "rewrite beastpics.go from the scripts")

// TestBeastPics reads, from every ECL script, the picture shown before each
// fight's monsters are loaded: opSetupMonster's close-up (its third
// operand) or opPicture's, the nearest before the opLoadMonster in the
// block. The kind's most common one is its bestiary picture (beastPics);
// -update rewrites beastpics.go.
func TestBeastPics(t *testing.T) {
	e := testEngine(t)
	count := map[string]map[int]int{}
	for disk := 1; disk <= 1; disk++ { // every disk's ECL holds the same blocks (dax siblings)
		for block := 1; block < 0x40; block++ {
			b := e.L.Block(fmt.Sprintf("ECL%d", disk), block)
			if len(b) < 2 {
				continue
			}
			_, lines, _ := walkECL(b[2:])
			pic := -1
			for _, pc := range sortedPCs(lines) {
				l := lines[pc]
				lit := func(i int) int {
					if i >= len(l.args) {
						return -1
					}
					n, err := strconv.Atoi(l.args[i])
					if err != nil {
						return -1
					}
					return n
				}
				switch l.name {
				case "opSetupMonster":
					pic = lit(2)
				case "opPicture":
					pic = lit(0)
				case "opLoadMonster":
					idx := lit(0)
					if pic < 0 || pic == 0xFF || idx < 0 {
						continue
					}
					c := &Character{}
					if e.L.Block(e.set.file("MON")+"CHA", idx) == nil || !e.LoadMonster(idx, c) {
						continue
					}
					if bt := beastOf(c.Name()); bt != nil {
						if count[bt.Name] == nil {
							count[bt.Name] = map[int]int{}
						}
						count[bt.Name][pic]++
					}
				}
			}
		}
	}
	got := map[string]int{}
	for name, m := range count {
		best := -1
		for k, n := range m {
			if best < 0 || n > m[best] || n == m[best] && k < best {
				best = k
			}
		}
		got[name] = best
	}
	if *updatePics {
		var s strings.Builder
		s.WriteString("// Code generated by TestBeastPics -update; DO NOT EDIT.\n\npackage engine\n\n// beastPics is each kind's picture in the picture window when the scripts\n// set its fight up (the PIC block: DOS and Amiga number them alike).\nvar beastPics = map[string]int{\n")
		names := make([]string, 0, len(got))
		for n := range got {
			names = append(names, n)
		}
		slices.Sort(names)
		for _, n := range names {
			fmt.Fprintf(&s, "\t%q: %d,\n", n, got[n])
		}
		s.WriteString("}\n")
		if err := os.WriteFile("beastpics.go", []byte(s.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	for n, p := range got {
		if beastPics[n] != p {
			t.Errorf("%s: scripts give %v, beastPics %v (go test -run TestBeastPics -update)", n, p, beastPics[n])
		}
	}
	if len(got) != len(beastPics) {
		t.Errorf("%d kinds from the scripts, %d in beastPics", len(got), len(beastPics))
	}
}
